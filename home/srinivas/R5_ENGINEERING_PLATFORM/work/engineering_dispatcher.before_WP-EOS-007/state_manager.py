"""CURRENT_STATE.md (managed section only) and R5_HANDOVER.md (generated on an unexpected exit)."""

from __future__ import annotations

import os
import tempfile
from pathlib import Path
from typing import Any

from .queue_manager import utc_now

BEGIN = "<!-- DISPATCHER_STATE_BEGIN -->"
END = "<!-- DISPATCHER_STATE_END -->"


def _atomic_text(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor, temporary = tempfile.mkstemp(dir=str(path.parent), prefix=".tmp-", suffix=".md")
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8") as handle:
            handle.write(text)
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(temporary, path)
    except BaseException:
        try:
            os.unlink(temporary)
        except FileNotFoundError:
            pass
        raise


def _recent_table(recent: list[dict[str, Any]]) -> list[str]:
    if not recent:
        return ["No packages dispatched yet."]
    rows = ["| Package | State | Worker | Finished (UTC) |", "|---|---|---|---|"]
    rows += [f"| {r['package_id']} | {r['state']} | {r['worker']} | {r['finished_at']} |" for r in reversed(recent[-10:])]
    return rows


class StateManager:
    def __init__(self, current_state_path: Path | str, handover_path: Path | str, archive_dir: Path | str) -> None:
        self.current_state_path = Path(current_state_path)
        self.handover_path = Path(handover_path)
        self.archive_dir = Path(archive_dir)

    # ------------------------------------------------------------------ CURRENT_STATE.md
    def render_block(self, snapshot: dict[str, Any]) -> str:
        counts = snapshot["queue"]
        lines = [BEGIN, f"## Engineering Dispatcher status ({snapshot.get('updated_at', utc_now())})", "",
                 "| READY | RUNNING | DONE | FAILED | REVIEW |", "|---|---|---|---|---|",
                 "| " + " | ".join(str(counts[s]) for s in ("READY", "RUNNING", "DONE", "FAILED", "REVIEW")) + " |", ""]
        running = snapshot.get("running") or []
        lines.append("Running: " + (", ".join(running) if running else "none"))
        lines += ["", *_recent_table(snapshot.get("recent", [])), END]
        return "\n".join(lines) + "\n"

    def update_current_state(self, snapshot: dict[str, Any]) -> None:
        """Replace the managed block (or append it); everything outside the markers is preserved byte for byte."""
        block = self.render_block(snapshot)
        text = self.current_state_path.read_text(encoding="utf-8") if self.current_state_path.exists() else "# CURRENT_STATE\n"
        if BEGIN in text and END in text and text.index(BEGIN) < text.index(END):
            head, rest = text.split(BEGIN, 1)
            _, tail = rest.split(END, 1)
            updated = head + block.rstrip("\n") + tail
        else:
            updated = text.rstrip("\n") + "\n\n" + block
        _atomic_text(self.current_state_path, updated)

    # ------------------------------------------------------------------ R5_HANDOVER.md
    def write_handover(self, reason: str, snapshot: dict[str, Any], requeued: list[str], traceback_text: str = "") -> Path:
        """Archive any existing handover, then write a fresh one describing the interrupted dispatcher."""
        if self.handover_path.exists():
            self.archive_dir.mkdir(parents=True, exist_ok=True)
            stamp = utc_now().replace(":", "").replace("+", "Z")
            (self.archive_dir / f"R5_HANDOVER.{stamp}.md").write_bytes(self.handover_path.read_bytes())
        counts = snapshot["queue"]
        lines = ["# R5 HANDOVER (generated by the Engineering Dispatcher)", "",
                 f"Generated: {utc_now()}", "", "## Why this exists", reason, "",
                 "## Queue at exit", "| READY | RUNNING | DONE | FAILED | REVIEW |", "|---|---|---|---|---|",
                 "| " + " | ".join(str(counts[s]) for s in ("READY", "RUNNING", "DONE", "FAILED", "REVIEW")) + " |", "",
                 "## Interrupted work",
                 ("Returned to READY for re-dispatch: " + ", ".join(requeued)) if requeued else "No package was RUNNING.", "",
                 "## Recent receipts", *_recent_table(snapshot.get("recent", [])), ""]
        if traceback_text:
            lines += ["## Exception", "```text", traceback_text.rstrip(), "```", ""]
        lines += ["## Resume", "Run `python -m engineering_dispatcher.dispatcher --drain` from the platform root; receipts are in "
                  "`receipts/dispatcher/` and the event log in `logs/dispatcher.log`.", ""]
        _atomic_text(self.handover_path, "\n".join(lines))
        return self.handover_path
